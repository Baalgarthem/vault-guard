class ConfirmDeleteModal extends obsidian.Modal {
    constructor(app, file, caller, isBlockedFormat, stats, callback) {
        super(app);
        this.file = file;
        this.caller = caller;
        this.isBlockedFormat = isBlockedFormat;
        this.stats = stats;
        this.callback = callback;
    }

    onOpen() {
        try {
            const { contentEl } = this;
            contentEl.empty();
            contentEl.addClass("vg-modal-confirm");

            const descriptor = app.plugins.getPlugin("vault-guard").getEntityDescriptor(this.file);
            const isFolder = descriptor.type === "carpeta";

            const titleText = isFolder 
                ? "Confirmar Eliminación de Carpeta" 
                : (descriptor.type === "nota" ? "Confirmar Eliminación de Nota" : "Confirmar Eliminación de Archivo");

            contentEl.createEl("h3", { text: titleText });

            // File/Folder Details Box
            const fileBox = contentEl.createDiv({ cls: "vg-modal-file-box" });
            const nameRow = fileBox.createDiv({ cls: "vg-modal-file-row" });
            nameRow.createDiv({ cls: "vg-modal-label", text: `Nombre de ${descriptor.article.toLowerCase()} ${descriptor.noun}:` });
            nameRow.createDiv({ cls: "vg-modal-file-name", text: descriptor.name });

            const pathRow = fileBox.createDiv({ cls: "vg-modal-file-row" });
            pathRow.createDiv({ cls: "vg-modal-label", text: "Ruta completa:" });
            pathRow.createDiv({ cls: "vg-modal-file-path", text: descriptor.path });

            if (isFolder && this.stats) {
                const statsRow = fileBox.createDiv({ cls: "vg-modal-file-row" });
                statsRow.createDiv({ cls: "vg-modal-label", text: "Contenido interno de la carpeta:" });
                statsRow.createDiv({
                    cls: "vg-modal-file-path",
                    text: `${this.stats.mdCount || 0} notas (.md), ${this.stats.otherCount || 0} otros archivos, ${this.stats.subfolderCount || 0} subcarpetas`
                });
            }

            // Explicit Solicitante Field Box
            renderSolicitanteBox(contentEl, this.caller);

            const questionText = isFolder 
                ? `ADVERTENCIA: ¿Deseas realmente eliminar la carpeta '${descriptor.name}' y todo su contenido?` 
                : `¿Deseas realmente eliminar ${descriptor.article.toLowerCase()} ${descriptor.noun} '${descriptor.name}'?`;
            contentEl.createEl("p", { text: questionText });

            // Vibrant Action Buttons (Sí / No)
            const btnRow = contentEl.createDiv({ cls: "vg-log-actions" });

            const cancelBtn = btnRow.createEl("button", { cls: "vg-btn vg-btn-no", text: "No, cancelar" });
            cancelBtn.addEventListener("click", () => {
                if (this.callback) this.callback(false);
                this.close();
            });

            const confirmBtn = btnRow.createEl("button", { cls: "vg-btn vg-btn-yes-danger", text: "Sí, eliminar" });
            confirmBtn.addEventListener("click", () => {
                if (this.callback) this.callback(true);
                this.close();
            });
        } catch (e) {
            console.error("Error en ConfirmDeleteModal:", e);
        }
    }

    onClose() {
        this.callback = null;
        this.contentEl.empty();
    }
}

// Modal 4: View Tracked Links Modal
class ViewLinksModal extends obsidian.Modal {
    constructor(app, entry) {
        super(app);
        this.entry = entry;
    }

    onOpen() {
        try {
            const { contentEl } = this;
            contentEl.empty();
            contentEl.addClass("vg-modal-confirm");

            const descriptor = app.plugins.getPlugin("vault-guard").getEntityDescriptor(this.entry.path || this.entry.name);
            contentEl.createEl("h3", { text: `Enlaces Asociados: ${descriptor.name}` });
            contentEl.createEl("p", { text: `A continuación se listan las notas vinculadas directas o mediante Virtual Linker a ${descriptor.article.toLowerCase()} ${descriptor.noun}:` });

            const linksBox = contentEl.createDiv({ cls: "vg-links-container" });

            const links = (this.entry && this.entry.links) ? this.entry.links : [];
            links.forEach(linkPath => {
                const row = linksBox.createDiv({ cls: "vg-link-row" });
                row.createSpan({ text: linkPath || "--" });

                const targetFile = this.app.vault.getAbstractFileByPath(linkPath);
                if (targetFile) {
                    row.createSpan({ cls: "vg-link-exists", text: "Existe en Bóveda" });
                } else {
                    row.createSpan({ cls: "vg-link-missing", text: "Enlace Roto / No Existe" });
                }
            });

            const btnRow = contentEl.createDiv({ cls: "vg-log-actions" });
            const closeBtn = btnRow.createEl("button", { cls: "vg-btn vg-btn-no", text: "Cerrar" });
            closeBtn.addEventListener("click", () => this.close());
        } catch (e) {
            console.error("Error en ViewLinksModal:", e);
        }
    }

    onClose() {
        this.contentEl.empty();
    }
}

// Settings Tab
class VaultGuardSettingTab extends obsidian.PluginSettingTab {
    constructor(app, plugin) {
        super(app, plugin);
        this.plugin = plugin;
    }

    display() {
        const { containerEl } = this;
        containerEl.empty();

        containerEl.createEl("h2", { text: "Configuración de Vault Guard" });

        // Setting 1: Total Guard
        new obsidian.Setting(containerEl)
            .setName("Total Guard")
            .setDesc("Bloquea la eliminación de cualquier nota .md o carpeta de la bóveda. Identifica e intercepta intentos de eliminación de plugins de terceros.")
            .addToggle(toggle => toggle
                .setValue(this.plugin.settings.totalGuard)
                .onChange(async value => {
                    this.plugin.settings.totalGuard = value;
                    await this.plugin.saveSettings();
                })
            );

        // Setting 2: Confirm Before Delete
        new obsidian.Setting(containerEl)
            .setName("Confirmar antes de eliminar")
            .setDesc("Muestra un cuadro de confirmación modal antes de eliminar cualquier nota, archivo o carpeta. Si son varios elementos, se preguntará de manera secuencial.")
            .addToggle(toggle => toggle
                .setValue(this.plugin.settings.confirmBeforeDelete)
                .onChange(async value => {
                    this.plugin.settings.confirmBeforeDelete = value;
                    await this.plugin.saveSettings();
                })
            );

        // Setting 3: Vault Guard Proprietary Advanced Startup Audit
        new obsidian.Setting(containerEl)
            .setName("Auditoría de Integridad al Inicio (Blindaje Inicial)")
            .setDesc("Escanea el registro de bóveda, grafo de enlaces y git diff al arrancar Obsidian para detectar elementos que desaparecieron mientras Obsidian estaba cerrado.")
            .addToggle(toggle => toggle
                .setValue(this.plugin.settings.enableIntegrityAudit)
                .onChange(async value => {
                    this.plugin.settings.enableIntegrityAudit = value;
                    await this.plugin.saveSettings();
                })
            );

        // Setting 3.1: Zoottelkeeper MOC Exclusion Toggle
        new obsidian.Setting(containerEl)
            .setName("Compatibilidad con Zoottelkeeper")
            .setDesc("Detecta automáticamente las etiquetas y palabras clave identificadoras de Zoottelkeeper (ej. Índice, MOC) y excluye sus archivos de índice del análisis de pérdidas.")
            .addToggle(toggle => toggle
                .setValue(this.plugin.settings.enableZoottelkeeperCompat)
                .onChange(async value => {
                    this.plugin.settings.enableZoottelkeeperCompat = value;
                    await this.plugin.saveSettings();
                })
            );

        // Setting 3.2: Trash Folder Startup Auto-Detection
        new obsidian.Setting(containerEl)
            .setName("Detectar Papelera (.trash) al Inicio")
            .setDesc("Si un archivo fue enviado a la papelera mientras Obsidian estaba cerrado, lo clasifica como 'En Papelera' en lugar de lanzar una falsa alarma de archivo totalmente perdido.")
            .addToggle(toggle => toggle
                .setValue(this.plugin.settings.checkTrashOnStartup)
                .onChange(async value => {
                    this.plugin.settings.checkTrashOnStartup = value;
                    await this.plugin.saveSettings();
                })
            );

        // Setting 4: Git Integration & Operations
        const isGitValid = this.plugin.isGitRepoValid;
        const gitSetting = new obsidian.Setting(containerEl)
            .setName("Integración con Repositorio Git")
            .setDesc(
                isGitValid
                    ? "Permite rastrear y buscar de forma automatizada archivos eliminados en el historial de commits de Git, con selector de rango de fechas (estilo r-calendar) y restauración en 1 clic."
                    : "DESACTIVADO: No se detectó una carpeta '.git' válida en la raíz de esta bóveda de Obsidian."
            )
            .addToggle(toggle => toggle
                .setValue(isGitValid ? this.plugin.settings.enableGitIntegration : false)
                .setDisabled(!isGitValid)
                .onChange(async value => {
                    if (isGitValid) {
                        this.plugin.settings.enableGitIntegration = value;
                        await this.plugin.saveSettings();
                    }
                })
            );

        if (!isGitValid) {
            gitSetting.controlEl.createDiv({
                cls: "vg-status-tag vg-status-purged",
                text: "Repositorio Git No Detectado"
            });
        }

        // Setting 4.1: Security Flag - Git Search Timeout
        new obsidian.Setting(containerEl)
            .setName("Límite de tiempo para búsquedas en Git (segundos)")
            .setDesc("Tiempo máximo en segundos que puede durar la búsqueda en el historial de Git antes de ser cancelada forzosamente por seguridad.")
            .addText(text => text
                .setPlaceholder("10")
                .setValue((this.plugin.settings.gitSearchTimeout || 10).toString())
                .onChange(async value => {
                    const parsed = parseInt(value, 10);
                    if (!isNaN(parsed) && parsed > 0) {
                        this.plugin.settings.gitSearchTimeout = parsed;
                        await this.plugin.saveSettings();
                    }
                })
            );

        // Setting 4.2: Respect .gitignore Setting (Disabled by default)
        new obsidian.Setting(containerEl)
            .setName("Respetar archivo .gitignore")
            .setDesc("Si existe un archivo .gitignore en la bóveda, omite de la protección y del registro de eliminaciones a todos los archivos y rutas definidos en él (Desactivado por defecto).")
            .addToggle(toggle => toggle
                .setValue(this.plugin.settings.respectGitignore)
                .onChange(async value => {
                    this.plugin.settings.respectGitignore = value;
                    this.plugin.gitignoreCache = null; // Clear cache on toggle
                    await this.plugin.saveSettings();
                })
            );

        // Setting 5: Protected Extensions
        new obsidian.Setting(containerEl)
            .setName("Formatos de archivo protegidos")
            .setDesc("Lista de extensiones separadas por comas que jamás deben eliminarse sin confirmación previa (Ejemplo: md, canvas, png). Por defecto se protegen todos los archivos en formato md.")
            .addText(text => text
                .setPlaceholder("md, canvas, png")
                .setValue(this.plugin.settings.blockedExtensions || "md")
                .onChange(async value => {
                    this.plugin.settings.blockedExtensions = value;
                    await this.plugin.saveSettings();
                })
            );

        // Setting 6: Reconstruct Link Network (Default: true)
        new obsidian.Setting(containerEl)
            .setName("Reconstruir red de enlaces al restaurar")
            .setDesc("Al restaurar una nota, analiza automáticamente sus enlaces directos/Virtual Linker y ofrece recuperar todos los archivos vinculados faltantes que estén en la papelera.")
            .addToggle(toggle => toggle
                .setValue(this.plugin.settings.reconstructLinkNetwork)
                .onChange(async value => {
                    this.plugin.settings.reconstructLinkNetwork = value;
                    await this.plugin.saveSettings();
                })
            );

        // Setting 7: Deletion Notifications
        new obsidian.Setting(containerEl)
            .setName("Notificaciones de eliminación")
            .setDesc("Muestra un aviso flotante (Notice) en Obsidian cada vez que una nota, archivo o carpeta es eliminado.")
            .addToggle(toggle => toggle
                .setValue(this.plugin.settings.notifyOnDelete)
                .onChange(async value => {
                    this.plugin.settings.notifyOnDelete = value;
                    await this.plugin.saveSettings();
                })
            );

        // Setting 8: Track Links
        new obsidian.Setting(containerEl)
            .setName("Rastrear enlaces directos y Virtual Linker")
            .setDesc("Analiza y guarda los enlaces internos [[...]] y referencias antes de que un elemento sea eliminado.")
            .addToggle(toggle => toggle
                .setValue(this.plugin.settings.trackLinks)
                .onChange(async value => {
                    this.plugin.settings.trackLinks = value;
                    await this.plugin.saveSettings();
                })
            );

        // Setting 8.1: Filter Tracked Links Only to Protected Formats
        new obsidian.Setting(containerEl)
            .setName("Filtrar enlaces rastreados solo a formatos protegidos")
            .setDesc("Al analizar las conexiones de una nota ([[WikiLinks]] y Virtual Linker), rastrea únicamente los enlaces que apunten a formatos de archivo protegidos (ej. .md, .canvas). Ignora enlaces a archivos no protegidos o de uso temporal.")
            .addToggle(toggle => toggle
                .setValue(this.plugin.settings.onlyTrackProtectedLinkFormats)
                .onChange(async value => {
                    this.plugin.settings.onlyTrackProtectedLinkFormats = value;
                    await this.plugin.saveSettings();
                })
            );

        // Setting 9: Max History Limit
        new obsidian.Setting(containerEl)
            .setName("Límite de historial de eliminaciones")
            .setDesc("Cantidad máxima de elementos eliminados a conservar en el log de Vault Guard (Por defecto: 100).")
            .addText(text => text
                .setPlaceholder("100")
                .setValue(this.plugin.settings.maxHistoryEntries.toString())
                .onChange(async value => {
                    const parsed = parseInt(value, 10);
                    if (!isNaN(parsed) && parsed > 0) {
                        this.plugin.settings.maxHistoryEntries = parsed;
                        await this.plugin.saveSettings();
                    }
                })
            );

        // Setting 10: Clear Log History Button
        new obsidian.Setting(containerEl)
            .setName("Vaciar registro de eliminaciones")
            .setDesc("Borra todos los elementos actualmente registrados en el historial de Vault Guard.")
            .addButton(btn => btn
                .setButtonText("Vaciar Historial")
                .setWarning()
                .onClick(async () => {
                    if (confirm("¿Estás seguro de que deseas vaciar el historial de eliminaciones?")) {
                        this.plugin.settings.deletedHistory = [];
                        await this.plugin.saveSettings();
                        new obsidian.Notice("[Vault Guard] Historial vaciado.");
                    }
                })
            );
    }
}

module.exports = VaultGuardPlugin;
