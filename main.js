// Modal 4: View Tracked Links Modal
class ViewLinksModal extends obsidian.Modal {
    constructor(app, entry) {
        super(app);
        this.entry = entry;
    }

    onOpen() {
        try {
            const { contentEl } = this;
            contentEl.empty();
            contentEl.addClass("vg-modal-confirm");

            const descriptor = app.plugins.getPlugin("vault-guard").getEntityDescriptor(this.entry.path || this.entry.name);
            contentEl.createEl("h3", { text: `Enlaces Asociados: ${descriptor.name}` });
            contentEl.createEl("p", { text: `A continuación se listan las notas vinculadas directas o mediante Virtual Linker a ${descriptor.article.toLowerCase()} ${descriptor.noun}:` });

            const linksBox = contentEl.createDiv({ cls: "vg-links-container" });

            const links = (this.entry && this.entry.links) ? this.entry.links : [];
            links.forEach(linkPath => {
                const row = linksBox.createDiv({ cls: "vg-link-row" });
                row.createSpan({ text: linkPath || "--" });

                const targetFile = this.app.vault.getAbstractFileByPath(linkPath);
                if (targetFile) {
                    row.createSpan({ cls: "vg-link-exists", text: "Existe en Bóveda" });
                } else {
                    row.createSpan({ cls: "vg-link-missing", text: "Enlace Roto / No Existe" });
                }
            });

            const btnRow = contentEl.createDiv({ cls: "vg-log-actions" });
            const closeBtn = btnRow.createEl("button", { cls: "vg-btn vg-btn-no", text: "Cerrar" });
            closeBtn.addEventListener("click", () => this.close());
        } catch (e) {
            console.error("Error en ViewLinksModal:", e);
        }
    }

    onClose() {
        this.entry = null;
        this.contentEl.empty();
    }
}

